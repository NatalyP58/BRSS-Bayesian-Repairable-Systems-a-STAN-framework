# Arithmetic Reduction of Age with Memory (ARAM) model functions
# ------------------------------------------------------------
# This file contains the core functions used for the ARAM model:
#   1. simulation of failure times under the ARAM,
#   2. conditional intensity function,
#   3. cumulative intensity at the truncation horizon, and
#   4. log-likelihood evaluation for multiple independent systems.
#

##############################     ARAM    ##############################################################################

gen_failures_ARAM <- function(k, param, time_trunc) {
  
  # Transformation used in the ARAM formulation to preserve
  # valid arguments inside the power terms
  h <- function(theta, beta) {
    if ((beta < 1 & theta >= 0) | (beta >= 1 & theta < 0)) {
      return(as.numeric(log((1 + theta) / (1 - theta)) * 10^4))
    } else {
      return(as.numeric(theta))
    }
  }
  h <- Vectorize(h, vectorize.args = "theta")
  
  # Sign correction used in the ARAM intensity representation
  sign <- function(beta) {
    ifelse(beta >= 1, 1, -1)
  }
  
  # Interval index containing time t
  k_t <- function(t, times, time_trunc) {
    findInterval(t, c(0, times, time_trunc), left.open = TRUE)
  }
  
  # Cumulative intensity up to time t for a given failure history
  lambda_ARAM_acum <- function(t, param, times, time_trunc) {
    if (t <= 0) return(0)
    
    beta  <- param[1]
    mu_T  <- param[2]
    theta <- param[3]
    
    kt      <- k_t(t, times, time_trunc)
    times0  <- c(0, times)[1:(kt - 1)]
    times1  <- c(times, time_trunc)[1:(kt - 1)]
    times_k <- ifelse(kt - 1 > 0, c(times, time_trunc)[kt - 1], 0)
    
    h_theta <- h(theta, beta)
    signo   <- sign(beta)
    
    if (kt - 1 > 0) {
      lambda1 <- (mu_T / time_trunc) *
        ((times1 - signo * h_theta * times0)^beta -
           (times0 - signo * h_theta * times0)^beta)
      lambda1[is.na(lambda1)] <- 0
    } else {
      lambda1 <- 0
    }
    
    lambda2 <- (mu_T / time_trunc) *
      ((t - signo * h_theta * times_k)^beta -
         (times_k - signo * h_theta * times_k)^beta)
    lambda2[is.na(lambda2)] <- 0
    
    return(sum(lambda1) + lambda2)
  }
  
  lambda_ARAM_acum <- Vectorize(lambda_ARAM_acum, vectorize.args = "t")
  
  # Objective function used to determine the next failure increment
  objective_increment <- function(x, param, t, times, time_trunc, u) {
    abs(
      lambda_ARAM_acum(t + x, param, times, time_trunc) -
        lambda_ARAM_acum(t, param, times, time_trunc) +
        log(1 - u)
    )
  }
  
  generate_system <- function(param, times, time_trunc) {
    current_time <- 0
    times <- numeric(0)
    
    # Failure times are generated by numerical inversion of the
    # cumulative intensity increment:
    # Lambda(t + x) - Lambda(t) = -log(1 - u)
    while (TRUE) {
      u <- runif(1)
      objective <- -log(1 - u)
      
      max_Lambda <- lambda_ARAM_acum(time_trunc, param, times, time_trunc) -
        lambda_ARAM_acum(current_time, param, times, time_trunc)
      
      # Stop if the next event cannot occur before the truncation horizon
      if (objective > max_Lambda) break
      
      result <- optimize(
        objective_increment,
        interval   = c(0, time_trunc - current_time),
        param      = param,
        t          = current_time,
        times      = times,
        time_trunc = time_trunc,
        u          = u
      )
      
      increment <- result$minimum
      next_time <- current_time + increment
      
      if (next_time > time_trunc) break
      
      times <- c(times, next_time)
      current_time <- next_time
    }
    
    return(times)
  }
  
  # Generate failure times for k independent systems
  replicate(k, generate_system(param, times, time_trunc), simplify = FALSE)
}

# Most recent failure time before t
indicator <- function(times, t) {
  vals <- times[times < t]
  if (length(vals) == 0) return(0)
  max(vals)
}

# Transformation used in the ARAM formulation
h <- function(theta, beta) {
  if ((beta < 1 & theta >= 0) | (beta >= 1 & theta < 0)) {
    return(as.numeric(log((1 + theta) / (1 - theta)) * 10^4))
  } else {
    return(as.numeric(theta))
  }
}
h <- Vectorize(h, vectorize.args = "theta")

# Sign correction used in the ARAM intensity representation
sign <- function(beta) {
  ifelse(beta >= 1, 1, -1)
}

lambda_ARAM <- function(t, param, times, time_trunc) {
  if (t <= 0) return(0)
  
  beta  <- param[1]
  mu_T  <- param[2]
  theta <- param[3]
  
  timess  <- indicator(times, t)
  h_theta <- h(theta, beta)
  signo   <- sign(beta)
  
  # ARAM conditional intensity function
  return((mu_T * beta / time_trunc) * (t - signo * h_theta * timess)^(beta - 1))
}

lambda_ARAM <- Vectorize(lambda_ARAM, vectorize.args = "t")

Lambda_ARAM <- function(param, times, time_trunc) {
  # Cumulative intensity evaluated at the truncation horizon T
  if (length(times) == 0 || max(times) <= 0) return(0)
  
  beta  <- param[1]
  mu_T  <- param[2]
  theta <- param[3]
  
  times0 <- c(0, times[-length(times)])
  times1 <- times
  timesp <- times[length(times)]
  
  h_theta <- h(theta, beta)
  signo   <- sign(beta)
  
  return(
    sum(
      (mu_T / time_trunc) *
        ((times1 - signo * h_theta * times0)^beta -
           (times0 - signo * h_theta * times0)^beta)
    ) +
      (mu_T / time_trunc) *
      ((time_trunc - signo * h_theta * timesp)^beta -
         (timesp - signo * h_theta * timesp)^beta)
  )
}

log_like_ARAM <- function(param, time_trunc, time) {
  
  log_like_single <- function(single_time) {
    if (length(single_time) == 0) return(0)
    
    # Log-likelihood contribution for one system:
    # sum of log intensities at observed failures
    # minus the cumulative intensity at the truncation time
    sum(log(lambda_ARAM(single_time, param, single_time, time_trunc))) -
      Lambda_ARAM(param, single_time, time_trunc)
  }
  
  # Total log-likelihood for k independent systems
  return(sum(sapply(time, log_like_single)))
}