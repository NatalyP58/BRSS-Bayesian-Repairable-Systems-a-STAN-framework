gen_failures_ARI <- function(k, param, time_trunc) {
  
  # Interval index containing time t
  k_t <- function(t, times, time_trunc) {
    findInterval(t, c(0, times, time_trunc), left.open = TRUE)
  }
  
  # Cumulative intensity up to time t for a given failure history
  lambda_ARI_acum <- function(t, param, times, time_trunc) {
    if (t <= 0) return(0)
    
    beta <- param[1]
    mu_T <- param[2]
    rho  <- param[3]
    
    kt <- k_t(t, times, time_trunc)
    times0 <- c(0, times)[1:(kt - 1)]
    times1 <- c(times, time_trunc)[1:(kt - 1)]
    times_k <- ifelse(kt - 1 > 0, c(times, time_trunc)[kt - 1], 0)
    
    if (kt - 1 > 0) {
      lambda1 <- (mu_T / time_trunc) *
        ((times1^beta - times0^beta) -
           rho * beta * times0^(beta - 1) * (times1 - times0))
      lambda1[is.na(lambda1)] <- 0
    } else {
      lambda1 <- 0
    }
    
    lambda2 <- (mu_T / time_trunc) *
      ((t^beta - times_k^beta) -
         rho * beta * times_k^(beta - 1) * (t - times_k))
    lambda2[is.na(lambda2)] <- 0
    
    return(sum(lambda1) + lambda2)
  }
  
  lambda_ARI_acum <- Vectorize(lambda_ARI_acum, "t")
  
  # Objective function used to determine the next failure increment
  objetivo_incremento <- function(x, param, t, times, time_trunc, u) {
    abs(
      lambda_ARI_acum(t + x, param, times, time_trunc) -
        lambda_ARI_acum(t, param, times, time_trunc) +
        log(1 - u)
    )
  }
  
  generate_system <- function() {
    current_time <- 0
    t <- numeric(0)
    
    # Failure times are generated by numerical inversion of the
    # cumulative intensity increment:
    # Lambda(t + x) - Lambda(t) = -log(1 - u),
    # which gives the next event increment x.
    while (TRUE) {
      times <- t
      u <- runif(1)
      objective <- -log(1 - u)
      
      max_Lambda <- lambda_ARI_acum(time_trunc, param, times, time_trunc) -
        lambda_ARI_acum(current_time, param, times, time_trunc)
      
      # Stop if the required cumulative increment exceeds the
      # remaining cumulative intensity up to the truncation horizon
      if (objective > max_Lambda) break
      
      result <- optimize(
        objetivo_incremento,
        interval = c(0, time_trunc - current_time),
        param = param,
        t = current_time,
        times = times,
        time_trunc = time_trunc,
        u = u
      )
      
      increment <- result$minimum
      next_time <- current_time + increment
      
      # Stop if the next failure exceeds the truncation horizon
      if (next_time > time_trunc) break
      
      current_time <- next_time
      t <- c(t, current_time)
    }
    
    t
  }
  
  # Generate failure times for k independent systems
  replicate(k, generate_system(), simplify = FALSE)
}

# Most recent failure time before t
indicator <- function(times, t) {
  vals <- times[times < t]
  if (length(vals) == 0) return(0)
  max(vals)
}

lambda_ARI <- function(t, param, times, time_trunc) {
  if (t <= 0) return(0)
  
  beta <- param[1]
  mu_T <- param[2]
  rho  <- param[3]
  
  timess <- indicator(times, t)
  
  # ARI conditional intensity function
  return(mu_T * beta / time_trunc * (t^(beta - 1) - rho * timess^(beta - 1)))
}

lambda_ARI <- Vectorize(lambda_ARI, vectorize.args = "t")

Lambda_ARI <- function(param, times, time_trunc) {
  # Cumulative intensity evaluated at the truncation horizon T
  if (length(times) == 0 || max(times) <= 0) return(0)
  
  beta <- param[1]
  mu_T <- param[2]
  rho  <- param[3]
  
  times0 <- c(0, times[-length(times)])
  times1 <- times
  timesp <- times[length(times)]
  
  return(
    sum(
      mu_T / time_trunc *
        ((times1^beta - times0^beta) -
           rho * beta * times0^(beta - 1) * (times1 - times0))
    ) +
      mu_T / time_trunc *
      ((time_trunc^beta - timesp^beta) -
         rho * beta * timesp^(beta - 1) * (time_trunc - timesp))
  )
}

log_like_ARI <- function(param, time_trunc, time) {
  
  log_like_single <- function(single_time) {
    if (length(single_time) == 0) return(0)
    
    # Log-likelihood contribution for one system:
    # sum of log intensities at observed failures
    # minus the cumulative intensity at the truncation time
    sum(log(lambda_ARI(single_time, param, single_time, time_trunc))) -
      Lambda_ARI(param, single_time, time_trunc)
  }
  
  # Total log-likelihood for k independent systems
  return(sum(sapply(time, log_like_single)))
}