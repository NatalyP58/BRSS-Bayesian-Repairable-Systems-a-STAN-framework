# Partial Imperfect Repair (PIR) model functions
# ------------------------------------------------------------
# This file contains the core functions used for the PIR model:
#   1. simulation of failure times under the PIR,
#   2. conditional intensity function,
#   3. cumulative intensity at the truncation horizon, and
#   4. log-likelihood evaluation for multiple independent systems.
#

##############################     PIR    ##############################################################################

gen_failures_PIR <- function(k, param, time_trunc, tau) {
  
  # Transformation of the repair-effect parameter used to keep
  # the PIR formulation numerically stable across parameter regions
  h_theta <- function(theta, beta) {
    if ((beta < 1 & theta >= 0) || (beta >= 1 & theta < 0)) {
      return(log((1 + theta) / (1 - theta)) * 1e4)
    } else {
      return(theta)
    }
  }
  h_theta <- Vectorize(h_theta, "theta")
  
  # Additional transformation entering the PIR denominator
  g_theta <- function(theta) {
    return(theta)
  }
  g_theta <- Vectorize(g_theta, "theta")
  
  # Sign correction used in the PIR formulation
  signo_beta <- function(beta) {
    ifelse(beta >= 1, 1, -1)
  }
  
  # Interval index containing time t
  k_t <- function(t, tau, time_trunc) {
    findInterval(t, c(0, tau, time_trunc), left.open = TRUE)
  }
  
  # Cumulative intensity up to time t for a given set of change points
  lambda_PIR_acum <- function(t, param, tau, time_trunc) {
    if (t <= 0) return(0)
    
    beta  <- param[1]
    mu_T  <- param[2]
    theta <- param[3]
    
    kt    <- k_t(t, tau, time_trunc)
    tau0  <- c(0, tau)[1:(kt - 1)]
    tau1  <- c(tau, time_trunc)[1:(kt - 1)]
    tau_k <- ifelse(kt - 1 > 0, c(tau, time_trunc)[kt - 1], 0)
    
    h_val  <- h_theta(theta, beta)
    g_val  <- g_theta(theta)
    s_beta <- signo_beta(beta)
    
    if (kt - 1 > 0) {
      num <- (tau1 - s_beta * h_val * tau0)^beta -
        (tau0 - s_beta * h_val * tau0)^beta
      lambda1 <- mu_T * num / (time_trunc + g_val * tau0)
    } else {
      lambda1 <- 0
    }
    
    lambda1[is.na(lambda1)] <- 0
    
    num2 <- (t - s_beta * h_val * tau_k)^beta -
      (tau_k - s_beta * h_val * tau_k)^beta
    lambda2 <- mu_T * num2 / (time_trunc + g_val * tau_k)
    lambda2[is.na(lambda2)] <- 0
    
    return(sum(lambda1) + lambda2)
  }
  
  lambda_PIR_acum <- Vectorize(lambda_PIR_acum, "t")
  
  # Objective function used to determine the next failure increment
  objective_increment <- function(x, param, t, tau, time_trunc, u) {
    abs(
      lambda_PIR_acum(t + x, param, tau, time_trunc) -
        lambda_PIR_acum(t, param, tau, time_trunc) +
        log(1 - u)
    )
  }
  
  generate_system <- function(param, tau, time_trunc) {
    current_time <- 0
    failures <- numeric(0)
    
    # Failure times are generated by numerical inversion of the
    # cumulative intensity increment:
    # Lambda(t + x) - Lambda(t) = -log(1 - u)
    while (TRUE) {
      u <- runif(1)
      objective <- -log(1 - u)
      
      max_Lambda <- lambda_PIR_acum(time_trunc, param, tau, time_trunc) -
        lambda_PIR_acum(current_time, param, tau, time_trunc)
      
      # Stop if the next event cannot occur before the truncation horizon
      if (objective > max_Lambda) break
      
      result <- optimize(
        objective_increment,
        interval   = c(0, time_trunc - current_time),
        param      = param,
        t          = current_time,
        tau        = tau,
        time_trunc = time_trunc,
        u          = u
      )
      
      increment <- result$minimum
      next_time <- current_time + increment
      
      if (next_time > time_trunc) break
      
      failures <- c(failures, next_time)
      current_time <- next_time
    }
    
    return(failures)
  }
  
  # Generate failure times for k independent systems
  replicate(k, generate_system(param, tau, time_trunc), simplify = FALSE)
}

# Most recent change point before t
indicator <- function(vector, t) {
  vals <- vector[vector < t]
  if (length(vals) == 0) return(0)
  max(vals)
}

# Transformation of the repair-effect parameter used in the PIR model
h <- function(theta, beta) {
  if ((beta < 1 & theta >= 0) | (beta >= 1 & theta < 0)) {
    return(as.numeric(log((1 + theta) / (1 - theta)) * 10^4))
  } else {
    return(as.numeric(theta))
  }
}
h <- Vectorize(h, vectorize.args = "theta")

# Additional transformation entering the PIR denominator
g <- function(theta) {
  return(theta)
}
g <- Vectorize(g, "theta")

# Sign correction used in the PIR formulation
sign <- function(beta) {
  ifelse(beta >= 1, 1, -1)
}

lambda_PIR <- function(t, param, tau, time_trunc) {
  if (t <= 0) return(0)
  
  beta  <- param[1]
  mu_T  <- param[2]
  theta <- param[3]
  
  taus    <- indicator(tau, t)
  h_theta <- h(theta, beta)
  signo   <- sign(beta)
  g_theta <- g(theta)
  
  # PIR conditional intensity function
  return(
    mu_T * beta / (time_trunc + g_theta * taus) *
      (t - signo * h_theta * taus)^(beta - 1)
  )
}

lambda_PIR <- Vectorize(lambda_PIR, vectorize.args = "t")

Lambda_PIR <- function(param, tau, time_trunc) {
  # Cumulative intensity evaluated at the truncation horizon T
  if (length(tau) == 0 || max(tau) <= 0) return(0)
  
  beta  <- param[1]
  mu_T  <- param[2]
  theta <- param[3]
  
  tau0 <- c(0, tau[-length(tau)])
  tau1 <- tau
  taup <- tau[length(tau)]
  
  h_theta <- h(theta, beta)
  g_theta <- g(theta)
  signo   <- sign(beta)
  
  return(
    sum(
      mu_T / (time_trunc + g_theta * tau0) *
        ((tau1 - signo * h_theta * tau0)^beta -
           (tau0 - signo * h_theta * tau0)^beta)
    ) +
      mu_T *
      ((time_trunc - signo * h_theta * taup)^beta -
         (taup - signo * h_theta * taup)^beta) /
      (time_trunc + g_theta * taup)
  )
}

log_like_PIR <- function(param, times, tau, time_trunc) {
  
  log_like_single <- function(times_i) {
    if (length(times_i) == 0) return(0)
    
    # Log-likelihood contribution for one system:
    # sum of log intensities at observed failures
    # minus the cumulative intensity at the truncation time
    sum(log(lambda_PIR(times_i, param, tau, time_trunc))) -
      Lambda_PIR(param, tau, time_trunc)
  }
  
  # Total log-likelihood for k independent systems
  return(sum(sapply(times, log_like_single)))
}