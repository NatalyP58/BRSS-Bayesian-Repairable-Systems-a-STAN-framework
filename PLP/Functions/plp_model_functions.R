# Power Law Process (PLP) model functions
# ------------------------------------------------------------
# This file contains the core functions used for the PLP model:
#   1. simulation of failure times under the PLP,
#   2. conditional intensity function,
#   3. cumulative intensity at the truncation horizon, and
#   4. log-likelihood evaluation for multiple independent systems.
#


##############################     PLP    ##############################################################################

gen_failures_PLP <- function(k, param, time_trunc) {
  beta <- param[1]
  mu_T <- param[2]
  
  generate_system <- function() {
    t <- numeric(0)
    current_time <- 0
    
    # Failure times are generated by inversion of the cumulative intensity:
    # Lambda(t + x) - Lambda(t) = -log(1 - u),
    # which gives the next event increment x.
    while (TRUE) {
      u <- runif(1)
      increment <- (current_time^beta + (time_trunc / mu_T) * (-log(1 - u)))^(1 / beta) - current_time
      
      # Stop if the next failure exceeds the truncation horizon
      if (current_time + increment > time_trunc) break
      
      current_time <- current_time + increment
      t <- c(t, current_time)
    }
    
    t
  }
  
  # Generate failure times for k independent systems
  replicate(k, generate_system(), simplify = FALSE)
}





lambda_PLP <- function(t, param, time_trunc) {
  beta <- param[1]
  mu_T <- param[2]
  
  # PLP conditional intensity function
  return((mu_T * beta / time_trunc) * t^(beta - 1))
}

lambda_PLP <- Vectorize(lambda_PLP, vectorize.args = "t")

Lambda_PLP <- function(param, time_trunc) {
  beta <- param[1]
  mu_T <- param[2]
  
  # Cumulative intensity evaluated at the truncation horizon T
  return((mu_T / time_trunc) * time_trunc^beta)
}



log_like_PLP <- function(param, time_trunc, time) {
  
  log_like_single <- function(single_time) {
    # Log-likelihood contribution for one system:
    # sum of log intensities at observed failures
    # minus the cumulative intensity at the truncation time
    sum(log(lambda_PLP(single_time, param, time_trunc))) - Lambda_PLP(param, time_trunc)
  }
  
  # Total log-likelihood for k independent systems
  return(sum(sapply(time, log_like_single)))
}

